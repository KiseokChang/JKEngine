MouseManager::MouseManager():
	MessageCreator(),CursorShowFlag(0),
	CursorID(0xffff),CursorImgeBuffer(0)
{
	PressingDelay=1000;
	PressingInterval  =300;

	DWORD mouseVec;
	copyFromLow(&mouseVec,0x0000,0x33*4,4);
	BYTE FirstInstruction;
	copyFromLow(&FirstInstruction,LOWORD(mouseVec),HIWORD(mouseVec),1);
	if(!mouseVec || FirstInstruction == 0xCF) CreationError=TRUE;
	else{
		union REGS regs;
		regs.w.ax=0;
		int386(0x33,&regs,&regs);
		uint16 result=regs.w.ax;
		if(result!= 65535) CreationError=TRUE;
		else{
			SetCursorID(0);
			SetActiveRegion(JKRect(0,0,getmaxx(),getmaxy()));
			InitEventHandler();
			CreationError=FALSE;
			ShowCursor();
		}
	}
}


