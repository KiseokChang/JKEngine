BOOL MouseManager::GetCurrentStatus()
{
	if(CreationError) return FALSE;
	BOOL ChangeStatus=FALSE;

	JKPoint OldPos=LastCheckPos;
	union REGS regs;
	regs.w.ax=3;
	int386(0x33,&regs,&regs);
	uint16 button=regs.w.bx;
	LastCheckPos.Set(regs.w.cx,regs.w.dx);
	if(0x0001&button){
		if(!LeftButton){
			LeftEvent.EventID = CLICK;
			LeftEvent.DelayCount=0;
			ChangeStatus =TRUE;
		}
		else{
			if(OldPos != LastCheckPos){
				LeftEvent.EventID = DRAGGING;
				LeftEvent.DelayCount=0;
				ChangeStatus =TRUE;
			}
			else{
				if(LeftEvent.DelayCount<PressingDelay){
					LeftEvent.EventID = NOACTION;
					LeftEvent.DelayCount++;
				}
				else {
					LeftEvent.EventID = PRESSING;
					LeftEvent.DelayCount-=PressingInterval;
					ChangeStatus =TRUE;
				}
			}
		}
		LeftButton = TRUE;
	}
	else{
		if(!LeftButton){
			if(OldPos != LastCheckPos){
				LeftEvent.EventID = NAVIGATE;
				LeftEvent.DelayCount=0;
				ChangeStatus =TRUE;
			}
			else{
				if(LeftEvent.DelayCount<PressingDelay){
					LeftEvent.EventID = NOACTION;
					LeftEvent.DelayCount++;
				}
				else {
					LeftEvent.EventID = STAYING;
					LeftEvent.DelayCount-=PressingInterval;
					ChangeStatus =TRUE;
				}
			}
		}
		else{
			LeftEvent.EventID = RELEASE;
			LeftEvent.DelayCount=0;
			ChangeStatus =TRUE;
		}
		LeftButton = FALSE;
	}

	if(0x0002&button){
		if(!RightButton){
			RightEvent.EventID = CLICK;
			RightEvent.DelayCount=0;
			ChangeStatus =TRUE;
		}
		else{
			if(OldPos != LastCheckPos){
				RightEvent.EventID = DRAGGING;
				RightEvent.DelayCount=0;
				ChangeStatus =TRUE;
			}
			else{
				if(RightEvent.DelayCount<PressingDelay){
					RightEvent.EventID = NOACTION;
					RightEvent.DelayCount++;
				}
				else {
					RightEvent.EventID = PRESSING;
					RightEvent.DelayCount-=PressingInterval;
					ChangeStatus =TRUE;
				}
			}
		}
		RightButton = TRUE;
	}
	else{
		if(!RightButton){
			if(OldPos != LastCheckPos){
				RightEvent.EventID = NAVIGATE;
				RightEvent.DelayCount=0;
				ChangeStatus =TRUE;
			}
			else{
				if(RightEvent.DelayCount<PressingDelay){
					RightEvent.EventID = NOACTION;
					RightEvent.DelayCount++;
				}
				else {
					RightEvent.EventID = STAYING;
					RightEvent.DelayCount-=PressingInterval;
					ChangeStatus =TRUE;
				}
			}
		}
		else{
			RightEvent.EventID = RELEASE;
			RightEvent.DelayCount=0;
			ChangeStatus =TRUE;
		}
		RightButton = FALSE;
	}
	return ChangeStatus;
}

