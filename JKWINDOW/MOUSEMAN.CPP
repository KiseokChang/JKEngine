void MouseManager::ShowCursor()
{
	if(CreationError) return;
	if(!CursorShowFlag)	{
		CursorImgeBuffer = new BYTE[16*16+4];
		DrawCursor(GetCursorPos(),0x01);
	}
	CursorShowFlag++;
}
void MouseManager::HideCursor()
{
	if(CreationError) return;
	CursorShowFlag--;
	if(!CursorShowFlag)	{
		DrawCursor(JKPoint(),0x02);
		if(CursorImgeBuffer) {
			delete[] CursorImgeBuffer;
			CursorImgeBuffer=0;
		}
	}
}

