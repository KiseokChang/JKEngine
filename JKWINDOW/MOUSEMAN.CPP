BOOL MouseManager::SetCursorID(WORD resid)
{
	if(CursorID==resid) {
		return FALSE;
	}

	if(CursorShowFlag>0) DrawCursor(JKPoint(),0x02);
	if(resid>=InternalCursorCount){
		ResourceBase *res=ResMan->GetResource(resid,RES_CURSOR);
		if(res){
			BYTE *data = res->AllocRealData();
			if(data)	{
				memcpy(&CursorBuffer,data,sizeof(CursorBuffer));
				res->FreeRealData(data);
				CursorID=resid;
				if(CursorShowFlag>0) DrawCursor(GetCursorPos(),0x01);
				return TRUE;
			}
		}
		resid=0;
	}
	CursorBuffer=InternalCursor[resid];
	CursorID=resid;
	if(CursorShowFlag>0) DrawCursor(GetCursorPos(),0x01);
	return TRUE;
}

