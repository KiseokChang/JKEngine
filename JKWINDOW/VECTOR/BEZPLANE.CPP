void BezierPlane::NormalizeControlPoint(JKRect rect,JKPoint points[4][4])
{
	uint16 width=rect.Width();
	uint16 height=rect.Height();
	for(uint16 i=0;i<4;i++){
		for(uint16 j=0;j<4;j++){
			points[i][j].Set(rect.left+width*i/3,rect.top+height*j/3);
		}
	}
}

JKPoint BezierPlane::CalcBezPoint(double u,double v,JKPoint points[4][4],BOOL iskbez)
{
	double table[2][4];
	if(iskbez){
		table[0][0]=1./2.*(1.-3.*u)*(2.-3.*u)*(1.-u);
		table[0][1]=9./2.*(2.-3.*u)*(1.-u)*u;
		table[0][2]=-9./2.*(1.-u)*u*(1.-3.*u);
		table[0][3]=1./2.*u*(1.-3*u)*(2.-3.*u);

		table[1][0]=1./2.*(1.-3.*v)*(2.-3.*v)*(1.-v);
		table[1][1]=9./2.*(2.-3.*v)*(1.-v)*v;
		table[1][2]=-9./2.*(1.-v)*v*(1.-3.*v);
		table[1][3]=1./2.*v*(1.-3*v)*(2.-3.*v);
	}
	else{
		table[0][0]=(1-u)*(1-u)*(1-u);
		table[0][1]=3*u*(1-u)*(1-u);
		table[0][2]=3*u*u*(1-u);
		table[0][3]=u*u*u;

		table[1][0]=(1-v)*(1-v)*(1-v);
		table[1][1]=3*v*(1-v)*(1-v);
		table[1][2]=3*v*v*(1-v);
		table[1][3]=v*v*v;
	}
	double doublex=0,doubley=0;
	for(uint16 i=0;i<4;i++){
		for(uint16 j=0;j<4;j++){
			doublex+=table[0][i]*table[1][j]*points[i][j].x;
			doubley+=table[0][i]*table[1][j]*points[i][j].y;
		}
	}
	return JKPoint(int16(doublex+0.5),int16(doubley+0.5));
}

void BezierPlane::ChangeBezMode(BOOL mode,JKPoint points[4][4],JKPoint PointBuf[4][4])
{
	double doublex,doubley;
	for(uint16 i=0;i<16;i++){
		doublex=0.;
		doubley=0.;
		if(mode){
			for(uint16 j=0;j<16;j++){
				doublex+=B2K[i][j]*points[j/4][j%4].x;
				doubley+=B2K[i][j]*points[j/4][j%4].y;
			}
		}
		else{
			for(uint16 j=0;j<16;j++){
				doublex+=K2B[i][j]*points[j/4][j%4].x;
				doubley+=K2B[i][j]*points[j/4][j%4].y;
			}
		}
		PointBuf[i/4][i%4].x=int16(doublex+0.5);
		PointBuf[i/4][i%4].y=int16(doubley+0.5);
	}
}

void BezierPlane::GetCurvePoint(BOOL iskbez,BOOL isu,double uv,JKPoint points[4][4],JKPoint PointBuf[4])
{
	double table[4];
	if(iskbez){
		table[0]=1./2.*(1.-3.*uv)*(2.-3.*uv)*(1.-uv);
		table[1]=9./2.*(2.-3.*uv)*(1.-uv)*uv;
		table[2]=-9./2.*(1.-uv)*uv*(1.-3.*uv);
		table[3]=1./2.*uv*(1.-3*uv)*(2.-3.*uv);
	}
	else{
		table[0]=(1-uv)*(1-uv)*(1-uv);
		table[1]=3*uv*(1-uv)*(1-uv);
		table[2]=3*uv*uv*(1-uv);
		table[3]=uv*uv*uv;
	}
	for(uint16 i=0;i<4;i++){
		double doublex=0,doubley=0;
		if(isu){
			for(uint16 j=0;j<4;j++){
				doublex+=table[j]*points[i][j].x;
				doubley+=table[j]*points[i][j].y;
			}
		}
		else{
			for(uint16 j=0;j<4;j++){
				doublex+=table[j]*points[j][i].x;
				doubley+=table[j]*points[j][i].y;
			}
		}
		PointBuf[i]=JKPoint(int16(doublex+0.5),int16(doubley+0.5));
	}
}