#!/usr/bin/env bash
# install_android_sdk.sh — #114 JK APK (T1) Android build-chain provisioner.
#
# Purpose : idempotent, source-tree-free provisioning of the toolchain needed
#           to `gradle assembleDebug` the thin-typing jkapk APK (v1 — Kotlin/JVM
#           only; NDK is a v2 deliverable and is NOT fetched here).
# Untracked: everything lands under the repo-root `build/android-sdk/` — covered
#           by the existing root `.gitignore` rule `build/` (verified with
#           `git check-ignore` in the T1 report). Nothing under build/ is ever
#           committed ("기계만 커밋" — D4).
# Network : only on first absence (each component is skipped when its marker
#           exists). Every download's sha256 is recorded in
#           build/android-sdk/downloads/SHA256SUMS.txt.
# Layout inside build/android-sdk/:
#   jdk17/                 Temurin 17 (AGP 8.x requires JDK 17)
#   cmdline-tools/latest/  Android commandline-tools (sdkmanager)
#   sdk/                   SDK root as handed to sdkmanager --sdk_root
#     platform-tools/ platforms/android-34/ build-tools/34.0.0/
#   gradle-8.9/            Gradle distribution (pinned by this script)
#   wrapper/               gradle wrapper (jar+scripts) generated by the
#                          pinned Gradle — wrapper jar is NOT committed; the
#                          module (engine/android/jkapk) keeps zero binaries
#                          and the wrapper property file points at the local
#                          zip so no re-download ever happens.
#   downloads/             zips + SHA256SUMS.txt
#   gradle-user-home/      GRADLE_USER_HOME (gradle caches, untracked)
#
# Usage: engine/tools/probes/install_android_sdk.sh
#        (then build: see the invocation line printed on success)
set -euo pipefail

PROG_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT_DIR="$(cd "$PROG_DIR/../../.." && pwd)"
SDK_ROOT="$ROOT_DIR/build/android-sdk"
DL_DIR="$SDK_ROOT/downloads"
SUMS="$DL_DIR/SHA256SUMS.txt"

JDK_URL="https://api.adoptium.net/v3/binary/latest/17/ga/windows/x64/jdk/hotspot/normal/eclipse"
JDK_ZIP="$DL_DIR/jdk17-windows-x64.zip"
CLT_URL="https://dl.google.com/android/repository/commandlinetools-win-11076708_latest.zip"
CLT_ZIP="$DL_DIR/commandlinetools-win-11076708_latest.zip"
GRADLE_VER="8.9"
GRADLE_URL="https://services.gradle.org/distributions/gradle-${GRADLE_VER}-bin.zip"
GRADLE_ZIP="$DL_DIR/gradle-${GRADLE_VER}-bin.zip"

PLATFORM="platforms;android-34"
BUILD_TOOLS="build-tools;34.0.0"

log() { echo "[install_android_sdk] $*"; }

mkdir -p "$DL_DIR"

need_extract() { # $1=marker path; returns 0 when marker MISSING (needs work)
  [ ! -e "$1" ]
}

record_sha256() { # $1=file
  local f="$1" name sum
  name="$(basename "$f")"
  sum="$(sha256sum "$f" | awk '{print $1}')"
  mkdir -p "$DL_DIR"
  if [ -f "$SUMS" ]; then
    grep -v -F "$name" "$SUMS" >"$SUMS.tmp" 2>/dev/null || true
    mv "$SUMS.tmp" "$SUMS"
  fi
  printf '%s  %s\n' "$sum" "$name" >>"$SUMS"
  log "sha256 $name = $sum (recorded in $SUMS)"
}

fetch() { # $1=url $2=dest
  if [ -f "$2" ]; then
    log "already present, skipping network: $(basename "$2")"
    # M-1 (T1 fix r1): a cached download must still match the recorded
    # sha256 (drift/corruption guard); first-run (no record) passes free.
    # park-5: first-run(SUMS 미기록) 무음 사망 소각 — grep 파산(파일 부재·
    # 미기록)이 pipefail로 set -e를 죽이는 길을 끊는다("first-run (no record)
    # passes free" 주석과 정합 — record_sha256의 || true 원존 동형).
    rec="$(grep -F "  $(basename "$2")" "$SUMS" 2>/dev/null | awk '{print $1}' || true)"
    got="$(sha256sum "$2" | awk '{print $1}')"
    if [ -n "$rec" ] && [ "$got" != "$rec" ]; then
      log "FATAL: sha256 mismatch for $(basename "$2") — recorded=$rec got=$got"
      exit 1
    fi
  else
    log "downloading $(basename "$2") ..."
    curl -fL --retry 3 --retry-delay 2 -o "$2.8part" "$1"
    mv "$2.8part" "$2"
  fi
  record_sha256 "$2"
}

unzip_to() { # $1=zip $2=targetdir
  mkdir -p "$2"
  unzip -q -o "$1" -d "$2"
}

# ---------------------------------------------------------------- 1. JDK 17
if need_extract "$SDK_ROOT/jdk17/bin/java.exe"; then
  fetch "$JDK_URL" "$JDK_ZIP"
  log "extracting JDK 17 ..."
  TMP="$SDK_ROOT/.tmp-jdk"; rm -rf "$TMP"; unzip_to "$JDK_ZIP" "$TMP"
  JDIR="$(find "$TMP" -maxdepth 1 -type d -name 'jdk-*' | head -1)"
  [ -n "$JDIR" ] || { log "FATAL: jdk dir not found in archive"; exit 1; }
  rm -rf "$SDK_ROOT/jdk17"
  mv "$JDIR" "$SDK_ROOT/jdk17"
  rm -rf "$TMP"
else
  log "JDK 17 marker present, skipping"
fi

# ------------------------------------------------- 2. commandline-tools (2)
if need_extract "$SDK_ROOT/cmdline-tools/latest/bin/sdkmanager.bat"; then
  fetch "$CLT_URL" "$CLT_ZIP"
  log "extracting commandline-tools ..."
  TMP="$SDK_ROOT/.tmp-clt"; rm -rf "$TMP"; unzip_to "$CLT_ZIP" "$TMP"
  mkdir -p "$SDK_ROOT/cmdline-tools"
  rm -rf "$SDK_ROOT/cmdline-tools/latest"
  mv "$TMP/cmdline-tools" "$SDK_ROOT/cmdline-tools/latest"
  rm -rf "$TMP"
else
  log "commandline-tools marker present, skipping"
fi

# -------------------------------------------------------- 3. Gradle distro
if need_extract "$SDK_ROOT/gradle-${GRADLE_VER}/bin/gradle.bat"; then
  fetch "$GRADLE_URL" "$GRADLE_ZIP"
  log "extracting Gradle ${GRADLE_VER} ..."
  TMP="$SDK_ROOT/.tmp-gradle"; rm -rf "$TMP"; unzip_to "$GRADLE_ZIP" "$TMP"
  rm -rf "$SDK_ROOT/gradle-${GRADLE_VER}"
  mv "$TMP/gradle-${GRADLE_VER}" "$SDK_ROOT/gradle-${GRADLE_VER}"
  rm -rf "$TMP"
else
  log "Gradle marker present, skipping"
fi

# ------------------------------------- 4. SDK packages via sdkmanager (2)
JDK_W="$(cygpath -w "$SDK_ROOT/jdk17")"
SDK_W="$(cygpath -m "$SDK_ROOT/sdk")"
SM="$SDK_ROOT/cmdline-tools/latest/bin/sdkmanager.bat"
export JAVA_HOME="$JDK_W"
[ -d "$SDK_ROOT/sdk" ] || mkdir -p "$SDK_ROOT/sdk"

run_sdkmanager() {
  # I-1 (T1 fix r1): under `set -euo pipefail` the `yes` feeder dies from
  # SIGPIPE(141) the moment sdkmanager.bat exits — expected, NOT a failure.
  # Tolerate 141/130 only; genuine failures still abort before the
  # fail-closed check block below (final honesty stays intact).
  local rc=0
  ( yes | "$SM" --sdk_root="$SDK_W" "$@" ) || rc=$?
  [ "$rc" -eq 141 ] || [ "$rc" -eq 130 ] || {
    log "FATAL: sdkmanager failed ($*) rc=$rc"; exit 1; }
}

if need_extract "$SDK_ROOT/sdk/platform-tools/adb.exe"; then
  log "accepting licenses + installing $PLATFORM $BUILD_TOOLS platform-tools ..."
  run_sdkmanager --licenses >/dev/null || true
  run_sdkmanager "platform-tools" "$PLATFORM" "$BUILD_TOOLS"
else
  log "SDK packages marker present (platform-tools), skipping sdkmanager"
fi

# ---------------------------------------------- 5. gradle wrapper (1종)
# Wrapper is generated by the pinned Gradle into the untracked dir above; the
# module sources stay binary-free. distributionUrl pins the LOCAL zip so the
# wrapper never hits the network again.
WRAP_DIR="$SDK_ROOT/wrapper"
GRADLE_USER_HOME="$SDK_ROOT/gradle-user-home"
export GRADLE_USER_HOME
if need_extract "$WRAP_DIR/gradle/wrapper/gradle-wrapper.jar"; then
  log "generating gradle wrapper into $WRAP_DIR ..."
  rm -rf "$WRAP_DIR"; mkdir -p "$WRAP_DIR/gradle/wrapper"
  printf 'rootProject.name = "jkapk-wrapper-gen"\n' >"$WRAP_DIR/settings.gradle.kts"
  GRADLE_BAT="$SDK_ROOT/gradle-${GRADLE_VER}/bin/gradle.bat"
  ( cd "$WRAP_DIR" && "$GRADLE_BAT" wrapper --gradle-version "$GRADLE_VER" \
      --distribution-type bin --no-daemon >/dev/null 2>&1 ) || {
    log "FATAL: gradle wrapper generation failed"; exit 1; }
  printf 'distributionBase=GRADLE_USER_HOME\ndistributionPath=wrapper/dists\ndistributionUrl=file\\:/%s\nnetworkTimeout=10000\nvalidateDistributionUrl=false\nzipStoreBase=GRADLE_USER_HOME\nzipStorePath=wrapper/dists\n' \
    "$(cygpath -m "$GRADLE_ZIP")" >"$WRAP_DIR/gradle/wrapper/gradle-wrapper.properties"
else
  log "gradle wrapper marker present, skipping"
fi

# ------------------------------------------------------------- 6. verify
fail=0
check() { # $1=label $2=path
  if [ -e "$2" ]; then
    log "PASS: $1 -> $(cygpath -m "$2")"
  else
    log "FAIL: $1 missing -> $2"
    fail=1
  fi
}
check "jdk17"                 "$SDK_ROOT/jdk17/bin/java.exe"
check "sdkmanager"            "$SDK_ROOT/cmdline-tools/latest/bin/sdkmanager.bat"
check "platform-tools/adb"    "$SDK_ROOT/sdk/platform-tools/adb.exe"
check "platform android-34"   "$SDK_ROOT/sdk/platforms/android-34"
check "build-tools 34.0.0"    "$SDK_ROOT/sdk/build-tools/34.0.0/apksigner.bat"
check "gradle $GRADLE_VER"    "$SDK_ROOT/gradle-${GRADLE_VER}/bin/gradle.bat"
check "gradle-wrapper jar"    "$WRAP_DIR/gradle/wrapper/gradle-wrapper.jar"
check "gradle-wrapper props"  "$WRAP_DIR/gradle/wrapper/gradle-wrapper.properties"
check "sha256 record"         "$SUMS"

if [ "$fail" -ne 0 ]; then exit 1; fi

cat <<EOF
[install_android_sdk] ALL PASS — toolchain provisioned (untracked).
[install_android_sdk] Build invocation (from repo root, bash):
  build/android-sdk/wrapper/gradlew.bat -p engine/android/jkapk assembleDebug
  (JAVA_HOME=build/android-sdk/jdk17 ANDROID_HOME=build/android-sdk/sdk \
GRADLE_USER_HOME=build/android-sdk/gradle-user-home required)
EOF